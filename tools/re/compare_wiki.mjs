// Compares the planner's wiki-sourced catalog (js/data.js) with the extracted game data
// (data/game/buildings.json) and writes data/game/WIKI_DIFF.md.
// usage: node tools/re/compare_wiki.mjs
import fs from 'node:fs';
import { WIKI_BUILDINGS as WIKI } from '../../js/data_wiki.js';
import { WIKI_TO_GAME } from './mapping.mjs';

const game = JSON.parse(fs.readFileSync('data/game/buildings.json', 'utf8')).data;
const actions = JSON.parse(fs.readFileSync('data/game/actions.json', 'utf8')).data;
const roads = JSON.parse(fs.readFileSync('data/game/roads.json', 'utf8')).data;
// Present each road/bridge as a building-like row so it can be compared the same way.
const roadRows = [];
for (const r of roads) {
  roadRows.push({ key: r.key, name: r.name, level: r.level, cost: r.cost.plain, power: 0, pollution: r.pollution, income: r.income });
  roadRows.push({ key: `${r.key}:river`, name: `${r.name} bridge (river)`, level: r.level, cost: r.cost.river_or_swamp, power: 0, pollution: r.pollution, income: r.income });
  roadRows.push({ key: `${r.key}:sea`, name: `${r.name} bridge (sea)`, level: r.level, cost: r.cost.sea, power: 0, pollution: r.pollution, income: r.income });
}
const forests = fs.existsSync('data/game/forests.json') ? JSON.parse(fs.readFileSync('data/game/forests.json', 'utf8')).data : [];
const forestRows = forests.map((f) => ({ key: `forest:${f.type}`, name: f.name, level: f.level, cost: f.cost, power: 0, pollution: f.pollution, income: f.income }));
const all = [...roadRows, ...forestRows, ...game, ...actions];
const byKey = Object.fromEntries([...all].reverse().map((b) => [b.key, b])); // first entry wins
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const byName = {};
for (const b of all) (byName[norm(b.name)] ||= []).push(b);


const fmt = (v) => (v == null ? '—' : typeof v === 'object' ? Object.entries(v).map(([k, x]) => `${k} ${Number(x).toLocaleString('en-US')}`).join(', ') || '—' : String(v));
const sameCost = (a, b) => JSON.stringify(Object.entries(a || {}).sort()) === JSON.stringify(Object.entries(b || {}).filter(([k]) => k !== 'gems' || (a && a.gems)).sort());

const rows = [], unmatched = [];
for (const w of WIKI) {
  const g = byKey[WIKI_TO_GAME[w.id]] || (byName[norm(w.name)] || [])[0];
  if (!g) { unmatched.push(w); continue; }
  const diffs = [];
  const lv = (x) => (x === 0 ? 1 : x ?? null); // level 0 = available from the start
  if (lv(w.lvl) !== lv(g.level)) diffs.push(['level', w.lvl, g.level]);
  if (!sameCost(w.cost, g.cost) && (w.cost || g.cost)) diffs.push(['cost', w.cost, g.cost]);
  if (g.power != null && (w.power ?? 0) !== g.power) diffs.push(['power', w.power ?? 0, g.power ?? 0]);
  if (g.pollution != null && (w.poll ?? 0) !== g.pollution) diffs.push(['pollution', w.poll ?? 0, g.pollution ?? 0]);
  for (const r of new Set([...Object.keys(w.income || {}), ...Object.keys(g.income || {})])) {
    if ((w.income?.[r] ?? 0) !== (g.income?.[r] ?? 0) && g.income?.[r] != null) diffs.push([`income.${r}`, w.income?.[r], g.income?.[r]]);
  }
  if (w.pave && g.pavement_bonus && Math.round(w.pave.mult * 100) !== g.pavement_bonus.percent) diffs.push(['pavement %', Math.round(w.pave.mult * 100), g.pavement_bonus.percent]);
  rows.push({ w, g, diffs });
}

const changed = rows.filter((r) => r.diffs.length);
const matchedKeys = new Set(rows.map((r) => r.g.key));
const missing = [...game, ...roadRows.filter((r) => !r.key.includes(':'))].filter((b) => !matchedKeys.has(b.key));

let md = `# Wiki vs game data\n\nGenerated by \`tools/re/compare_wiki.mjs\`. "Wiki" is the current \`js/data.js\`; "Game" is \`data/game/buildings.json\`\n(base values, no upgrades). Income is per 9 s tick.\n\n`;
md += `- Planner entries compared: **${rows.length}** (${unmatched.length} not found in game data)\n- Entries with at least one difference: **${changed.length}**\n- Game buildings the planner doesn't have yet: **${missing.length}**\n\n`;
md += `## Differences\n\n| Planner id | Game key | Field | Wiki | Game |\n|---|---|---|---|---|\n`;
for (const { w, g, diffs } of changed) for (const [f, a, b] of diffs) md += `| ${w.id} | ${g.key} | ${f} | ${fmt(a)} | ${fmt(b)} |\n`;
md += `\n## Planner entries not matched\n\n${unmatched.map((w) => `- ${w.id} (${w.name})`).join('\n') || 'None'}\n`;
md += `\n## Game buildings missing from the planner\n\n| Game key | Name | Level | Unlock |\n|---|---|---|---|\n`;
for (const b of missing) md += `| ${b.key} | ${b.name} | ${b.level ?? '—'} | ${b.unlock ?? "level"}${b.event_type ? ` (event ${b.event_type})` : ''} |\n`;
fs.writeFileSync('data/game/WIKI_DIFF.md', md);
console.log(`compared ${rows.length}, changed ${changed.length}, unmatched ${unmatched.length}, missing ${missing.length}`);
